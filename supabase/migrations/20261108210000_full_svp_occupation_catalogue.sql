CREATE OR REPLACE FUNCTION public.sync_svp_occupation_catalogue(_items jsonb)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
  source record;
  name_matches integer;
  changed integer;
  added integer := 0;
  linked integer := 0;
  kept integer := 0;
  conflicts integer := 0;
  total integer;
BEGIN
  IF _items IS NULL OR jsonb_typeof(_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Invalid occupation catalogue';
  END IF;
  IF jsonb_array_length(_items) < 1 OR jsonb_array_length(_items) > 10000 THEN
    RAISE EXCEPTION 'Invalid occupation catalogue size';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(_items) AS item
    WHERE jsonb_typeof(item->'key') IS DISTINCT FROM 'string'
       OR jsonb_typeof(item->'name') IS DISTINCT FROM 'string'
       OR btrim(item->>'key') !~ '^[0-9]{4,8}$'
       OR length(btrim(item->>'name')) NOT BETWEEN 1 AND 250
  ) OR (SELECT count(DISTINCT btrim(item->>'key')) FROM jsonb_array_elements(_items) AS item) <> jsonb_array_length(_items)
    OR (SELECT count(DISTINCT lower(btrim(item->>'name'))) FROM jsonb_array_elements(_items) AS item) <> jsonb_array_length(_items) THEN
    RAISE EXCEPTION 'Invalid or duplicate occupation catalogue entries';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('public.sync_svp_occupation_catalogue'));
  FOR source IN
    SELECT btrim(item->>'key') AS key, btrim(item->>'name') AS name
    FROM jsonb_array_elements(_items) AS item ORDER BY item->>'key'
  LOOP
    IF EXISTS (SELECT 1 FROM public.occupations WHERE svp_key = source.key) THEN
      kept := kept + 1;
      CONTINUE;
    END IF;
    SELECT count(*) INTO name_matches FROM public.occupations WHERE lower(btrim(name)) = lower(source.name);
    IF name_matches = 0 THEN
      INSERT INTO public.occupations(name, svp_key, active) VALUES (source.name, source.key, true);
      added := added + 1;
    ELSIF name_matches = 1 THEN
      UPDATE public.occupations SET svp_key = source.key
      WHERE lower(btrim(name)) = lower(source.name) AND nullif(btrim(svp_key), '') IS NULL;
      GET DIAGNOSTICS changed = ROW_COUNT;
      IF changed = 1 THEN linked := linked + 1;
      ELSE conflicts := conflicts + 1;
      END IF;
    ELSE
      conflicts := conflicts + 1;
    END IF;
  END LOOP;
  SELECT count(*) INTO total FROM public.occupations;
  RETURN jsonb_build_object('official', jsonb_array_length(_items), 'inserted', added,
    'linked', linked, 'unchanged', kept, 'conflicts', conflicts, 'total', total);
END;
$function$;
REVOKE ALL ON FUNCTION public.sync_svp_occupation_catalogue(jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sync_svp_occupation_catalogue(jsonb) TO service_role;

